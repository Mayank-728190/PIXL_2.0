from datetime import datetime
from typing import Optional, Dict, Any
from pydantic import BaseModel, Field


class MasterScreenCreateRequest(BaseModel):
    name: str = Field(..., min_length=2, max_length=255)
    organization_id: str = Field(..., description="Target Agency this screen is assigned to")
    site_id: Optional[str] = None
    orientation: str = Field(default="LANDSCAPE", pattern="^(LANDSCAPE|PORTRAIT)$")
    resolution: str = Field(default="1920x1080")


class DeviceEnrollChallengeRequest(BaseModel):
    hardware_fingerprint: str = Field(..., min_length=6, max_length=255)
    model: str = Field(default="Generic Signage Box", max_length=100)
    os_version: str = Field(default="Android 12", max_length=50)
    app_version: str = Field(default="2.0.0", max_length=50)


class DeviceEnrollChallengeResponse(BaseModel):
    challenge_id: str
    pin: str
    expires_at: datetime
    poll_interval_seconds: int = 3


class AgencyScreenClaimRequest(BaseModel):
    pin: str = Field(..., min_length=6, max_length=8)
    screen_id: Optional[str] = Field(None, description="Optional ID of screen pre-assigned by Master to this Agency")
    name: Optional[str] = None
    site_id: Optional[str] = None


class AgencyScreenClaimResponse(BaseModel):
    status: str = "CLAIMED"
    screen_id: str
    organization_id: str
    message: str = "Screen paired and activated successfully"


class DeviceEnrollExchangeRequest(BaseModel):
    challenge_id: str
    public_key_pem: str = Field(..., description="Asymmetric public key generated by Android Keystore")


class DeviceEnrollExchangeResponse(BaseModel):
    device_id: str
    device_token: str
    epoch: int = 1
    server_public_key_pem: str
    ws_endpoint: str


class ScreenHeartbeatRequest(BaseModel):
    device_id: str
    epoch: int = 1
    manifest_version: int = 0
    playback_state: str = "PLAYING"
    current_asset_id: Optional[str] = None
    storage_free_mb: Optional[int] = None
    cpu_temp_celsius: Optional[float] = None
    display_power_state: str = "ON"


class ScreenHeartbeatResponse(BaseModel):
    server_time: datetime
    latest_manifest_version: int
    action_required: Optional[str] = None


class ScreenResponse(BaseModel):
    id: str
    organization_id: Optional[str]
    site_id: Optional[str]
    name: str
    status: str
    orientation: str
    resolution: str
    current_manifest_version: int
    last_heartbeat_at: Optional[datetime]
    app_version: Optional[str]
    os_version: Optional[str]
    created_at: datetime

    class Config:
        from_attributes = True


class AdminPlayAdRequest(BaseModel):
    media_ids: list[str] = Field(default_factory=list, description="List of media asset UUIDs or integer numbers")
    media_id: Optional[str] = Field(None, description="Single media asset UUID or integer number")
    duration_seconds: int = Field(default=10, ge=1, le=86400, description="Duration per ad item in seconds")
    name: Optional[str] = Field(default="Live Ad Broadcast", max_length=255)
    priority: int = Field(default=200, ge=1, le=1000, description="Priority: 100=Standard, 200=High Ad Takeover, 300=Emergency")
    duration_hours: int = Field(default=24, ge=1, le=8760, description="How many hours this ad campaign remains active")


class AdminPlayAdResponse(BaseModel):
    screen_id: str
    screen_number: Optional[int] = None
    campaign_id: str
    campaign_name: str
    priority: int
    status: str = "PLAYING"
    manifest_version: int
    media_count: int
    media_items: list[dict]
    message: str = "Ad broadcast published. Screen will display the ad on its next sync cycle."


class ScreenPlaybackStatusResponse(BaseModel):
    screen_id: str
    screen_number: Optional[int] = None
    screen_name: str
    status: str
    is_online: bool
    manifest_version: int
    last_sync_at: Optional[datetime]
    current_campaign: Optional[dict] = None


